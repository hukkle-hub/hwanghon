const SWING=1.20, REACH=0.62;
function wide(rh,w){ if(w<=0.001) return rh; let [x,y,z]=[rh[0]*SWING,rh[1]*(1+(SWING-1)*0.6),rh[2]*SWING]; const r=Math.hypot(x,y,z);
  if(r>REACH){ const f=REACH/r; x*=f; y*=f; z*=f; } return [rh[0]+(x-rh[0])*w, rh[1]+(y-rh[1])*w, rh[2]+(z-rh[2])*w]; }
const lerp3=(a,b,k)=>a.map((v,i)=>v+(b[i]-v)*k);
/* rig_core.path_spec 과 같다: 키 사이 smoothstep, 가운데일수록 손을 몸에서 더 민다 */
export function pathSpec(keys,t){ const w=Math.max(0,Math.min(1,4*t*(1-t)));
  for(let i=0;i<keys.length-1;i++){ const [t0,a]=keys[i],[t1,b]=keys[i+1];
    if(t<=t1){ let k=t1<=t0?0:(t-t0)/(t1-t0); k=k*k*(3-2*k);
      return {rh:wide(lerp3(a.rh,b.rh,k),w), shaft:lerp3(a.shaft,b.shaft,k), blade:lerp3(a.blade,b.blade,k), left:a.left+(b.left-a.left)*k}; } }
  return {...keys[keys.length-1][1]}; }
